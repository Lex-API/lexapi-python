"""Retry policy: what to retry, and how long to wait (PLAN.md §1.2).

The governing rule is **billing safety**: the SDK retries automatically only
when the retry cannot charge the caller twice. LexAPI charges a request when
the credit middleware admits it and refunds a failure only when *the app
itself* finishes a 4xx/5xx response (``res.on('finish')`` in the API's
``middleware/credits.js``). So:

- a **429** is always safe (the per-key limiter runs before any charge);
- a **5xx generated by the LexAPI app** is refunded in full, so it is safe;
- a **5xx generated by a proxy** (Cloudflare 520/524, a gateway 502/504
  with an HTML or plain-text body) and a **dropped connection** after the
  request was sent are *not* refunded — the app may have charged and may
  still be running — so they are retried only for **free** operations;
- Cloudflare **521/522/523** and "never sent" transport failures mean the
  request never reached the app, so they are safe for any method.

App origin is recognised by a response header only the app sets:
``X-LexAPI-Version`` (every app response once lex-api #299 is deployed) or
``RateLimit-Limit`` (the per-key limiter sets the draft-6 ``RateLimit-*``
headers on every ``/api/v1`` response it passes, before any charge; Cloudflare,
the gateway and the load balancer never add them to their own error pages).
The body is never used — an intermediary can answer JSON with an ``error``
key. When the origin is unknown the response is treated as proxy-generated.

POST/PUT/DELETE are retried only on 429 and on never-reached failures. The
read-only POSTs (search, document reads, resolve, semantic search) may also
retry an app-origin 502/503/504 when ``RetryConfig.retry_read_only_posts`` is
set; webhook writes and tests never are.

Wait resolution (server-directed wins, clamped to ``backoff_cap``):

1. ``Retry-After`` header (delta-seconds or HTTP-date) on any status; an
   empty or unparseable value counts as absent,
2. on a 429 only: ``RateLimit-Reset`` (draft-6 delta-seconds; LexAPI sends
   ``RateLimit-*`` on every response, so outside a 429 it describes the rate
   window, not a retry time). ``X-RateLimit-*`` is not sent (legacy headers
   are disabled server-side) and is ignored,
3. on a 429 only: the JSON ``retryAfter`` body field,
4. exponential backoff with full jitter.

Numeric hints are delta-seconds; a value above 1e12 is read as epoch
milliseconds and above 1e9 as epoch seconds and converted to a delta.

A 429 that reports an exhausted *quota* (legacy plans: a ``usage`` block
with ``resetsAt`` and neither ``Retry-After`` nor ``retryAfter``) is never
retried — it cannot succeed before ``resetsAt``.
"""

from __future__ import annotations

import email.utils
import random
import time
from dataclasses import dataclass, field
from typing import Any

import httpx

#: Above this a numeric hint is epoch *seconds* (1e9 s ≈ 31.7 years of delta).
EPOCH_SECONDS_THRESHOLD = 1_000_000_000
#: Above this a numeric hint is epoch *milliseconds*.
EPOCH_MILLIS_THRESHOLD = 1_000_000_000_000

_IDEMPOTENT_METHODS = frozenset({"GET", "HEAD", "OPTIONS"})

#: Cloudflare could not reach the origin: web server down (521), connection
#: timed out (522), origin unreachable (523). The app never saw the request.
NOT_REACHED_STATUSES = frozenset({521, 522, 523})

#: App-origin statuses a read-only POST may retry under ``retry_read_only_posts``.
READ_ONLY_POST_STATUSES = frozenset({502, 503, 504})


def _default_retry_statuses() -> frozenset[int]:
    return frozenset({429, 502, 503, 504, 520, 521, 522, 523, 524})


def _default_non_idempotent_statuses() -> frozenset[int]:
    return frozenset({429})


@dataclass(frozen=True)
class RetryConfig:
    """Retry policy knobs. ``max_retries=0`` disables retries entirely.

    Attributes:
        max_retries: retries after the first attempt (default 3).
        backoff_base / backoff_cap: full-jitter backoff ``U(0, min(cap,
            base * 2**attempt))`` in seconds; the cap also clamps
            server-directed waits.
        retry_statuses: statuses ever considered for a retry. The
            billing-safety rule (module docstring) still decides per response.
        retry_statuses_non_idempotent: statuses retried for **every**
            POST/PUT/DELETE, webhook writes included, whatever their origin.
            Default ``{429}``. Widening it can duplicate webhooks or test
            deliveries and can double-charge — prefer ``retry_read_only_posts``.
        retry_read_only_posts: also retry the read-only POSTs (search,
            document reads, resolve, semantic search) on an **app-origin**
            502/503/504, which the API refunds in full. Default off; never
            applies to webhook create/update/test.
    """

    max_retries: int = 3
    backoff_base: float = 0.5
    backoff_cap: float = 30.0
    retry_statuses: frozenset[int] = field(default_factory=_default_retry_statuses)
    retry_statuses_non_idempotent: frozenset[int] = field(
        default_factory=_default_non_idempotent_statuses
    )
    retry_read_only_posts: bool = False


DEFAULT_RETRY_CONFIG = RetryConfig()


def compute_backoff(attempt: int, config: RetryConfig) -> float:
    """Exponential backoff with full jitter: ``U(0, min(cap, base * 2**attempt))``."""
    ceiling = min(config.backoff_cap, config.backoff_base * (2**attempt))
    return random.uniform(0, ceiling)


def _delta_from_number(value: float) -> float | None:
    """A numeric hint as delta-seconds, converting epoch ms / s defensively."""
    if value < 0:
        return None
    if value > EPOCH_MILLIS_THRESHOLD:
        return max(0.0, value / 1000.0 - time.time())
    if value > EPOCH_SECONDS_THRESHOLD:
        return max(0.0, value - time.time())
    return value


def parse_retry_after(value: str) -> float | None:
    """Parse a ``Retry-After`` header: delta-seconds or HTTP-date.

    Empty or unparseable values return ``None`` (treated as absent).
    """
    value = value.strip()
    if not value:
        return None
    try:
        seconds = float(value)
    except ValueError:
        try:
            when = email.utils.parsedate_to_datetime(value)
        except (TypeError, ValueError, IndexError):
            return None
        if when is None:
            return None
        return max(0.0, when.timestamp() - time.time())
    return _delta_from_number(seconds)


def _body_retry_after(body: Any) -> float | None:
    """JSON ``retryAfter`` field (delta-seconds; epoch values converted)."""
    if not isinstance(body, dict):
        return None
    raw = body.get("retryAfter")
    if isinstance(raw, bool) or not isinstance(raw, (int, float)):
        return None
    return _delta_from_number(float(raw))


def server_wait_hint(headers: httpx.Headers, body: Any, status: int | None = None) -> float | None:
    """Resolve the server-directed wait for a failed response, if any.

    ``Retry-After`` applies to any status. ``RateLimit-Reset`` and the JSON
    ``retryAfter`` apply to a 429 only. ``status=None`` (unknown) consults
    every source.
    """
    header = headers.get("retry-after")
    if header is not None:
        parsed = parse_retry_after(header)
        if parsed is not None:
            return parsed
    if status is not None and status != 429:
        return None
    reset = headers.get("ratelimit-reset")
    if reset is not None:
        try:
            seconds = _delta_from_number(float(reset.strip()))
        except ValueError:
            seconds = None
        if seconds is not None:
            return seconds
    return _body_retry_after(body)


def is_quota_exhausted(status: int, headers: httpx.Headers, body: Any) -> bool:
    """True for a 429 that reports an exhausted quota rather than a rate limit.

    lex-api #304 on: the body's top-level ``code`` is ``QUOTA_EXHAUSTED``
    (whatever else the response carries). Fallback for older servers: legacy
    daily-call plans (``"Daily quota exceeded"``) and the legacy monthly
    semantic quota answer 429 with a ``usage`` block carrying ``resetsAt``
    and no ``retryAfter`` / ``Retry-After``.
    """
    if status != 429:
        return False
    if isinstance(body, dict) and body.get("code") == "QUOTA_EXHAUSTED":
        return True
    if headers.get("retry-after") is not None:
        return False
    if not isinstance(body, dict) or "retryAfter" in body:
        return False
    usage = body.get("usage")
    return isinstance(usage, dict) and isinstance(usage.get("resetsAt"), str)


def is_app_response(headers: httpx.Headers, body: Any = None) -> bool:
    """Whether the LexAPI app itself produced this response (see module doc).

    ``body`` is accepted for signature stability and deliberately ignored.
    """
    return bool(headers.get("x-lexapi-version") or headers.get("ratelimit-limit"))


#: httpcore's message when the connection closes before the response head —
#: the stale keep-alive case. Matched exactly (as a prefix): h11's mid-body
#: "peer closed connection without sending complete message body" also says
#: "without sending" but arrives after the response started, so the app may
#: already have charged. httpx raises both as ``RemoteProtocolError`` with no
#: other state to tell them apart.
PRE_RESPONSE_DISCONNECT = "Server disconnected without sending a response"


def never_reached_app(exc: BaseException) -> bool:
    """Transport failures where the request provably never got to the app:
    connect errors and timeouts, pool exhaustion (nothing was sent), and a
    connection closed before any response byte (see
    :data:`PRE_RESPONSE_DISCONNECT`). A close after part of the response
    arrived is *not* in this set."""
    if isinstance(exc, (httpx.ConnectError, httpx.ConnectTimeout, httpx.PoolTimeout)):
        return True
    return isinstance(exc, httpx.RemoteProtocolError) and str(exc).startswith(
        PRE_RESPONSE_DISCONNECT
    )


def is_retryable_exception(exc: BaseException, method: str = "GET", *, free: bool = False) -> bool:
    """Transport-error retry rule.

    Never-reached failures are safe for any method. Any other transport
    error (read errors and timeouts after the request was sent) is retried
    only for a **free** idempotent operation — on a billed call the app may
    have charged and, with no finished error response, refunds nothing.
    """
    if never_reached_app(exc):
        return True
    return free and method.upper() in _IDEMPOTENT_METHODS and isinstance(exc, httpx.TransportError)


def retry_allowed(
    method: str,
    response: httpx.Response,
    body: Any,
    config: RetryConfig,
    *,
    read_only: bool = False,
    free: bool = False,
) -> bool:
    """The billing-safety decision for one failed response."""
    status = response.status_code
    idempotent = method.upper() in _IDEMPOTENT_METHODS
    if is_quota_exhausted(status, response.headers, body):
        return False
    if not idempotent and status in config.retry_statuses_non_idempotent:
        return True  # 429 by default; anything else is an explicit caller opt-in
    if status not in config.retry_statuses:
        return False
    if status == 429 or status in NOT_REACHED_STATUSES:
        return True
    if idempotent:
        return free or is_app_response(response.headers, body)
    return (
        read_only
        and config.retry_read_only_posts
        and status in READ_ONLY_POST_STATUSES
        and is_app_response(response.headers, body)
    )


def retry_wait(
    method: str,
    response: httpx.Response,
    body: Any,
    attempt: int,
    config: RetryConfig,
    *,
    read_only: bool = False,
    free: bool = False,
) -> float | None:
    """Seconds to sleep before retry *attempt*, or ``None`` for "don't retry"."""
    if attempt >= config.max_retries:
        return None
    if not retry_allowed(method, response, body, config, read_only=read_only, free=free):
        return None
    hint = server_wait_hint(response.headers, body, response.status_code)
    if hint is not None:
        return min(hint, config.backoff_cap)
    return compute_backoff(attempt, config)
