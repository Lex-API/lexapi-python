"""Retry policy: what to retry, and how long to wait (SDK contract §1.2,
``docs/sdk-contract.md`` in the repository).

The governing rule is **billing safety**: the SDK retries automatically only
when the retry cannot charge the caller twice. LexAPI charges a request when
it is admitted and refunds a failure only when *the app itself* answers
with a 4xx/5xx response. So:

- a **429** is always safe (the per-key limiter runs before any charge);
- a **5xx generated by the LexAPI app** is refunded in full, so it is safe;
- a **5xx generated by a proxy** (Cloudflare 520/524, a gateway 502/504
  with an HTML or plain-text body) and a **dropped connection** after the
  request was sent are *not* refunded — the app may have charged and may
  still be running — so they are retried only for **free** operations;
- Cloudflare **521/522/523** and "never sent" transport failures mean the
  request never reached the app, so they are safe for any method.

App origin is recognised by a response header only the app sets:
``X-LexAPI-Version`` (every app response from API 2.1.0 on) or
``RateLimit-Limit`` (the per-key limiter sets the draft-6 ``RateLimit-*``
headers on every ``/api/v1`` response it passes, before any charge; proxies
never add them to their own error pages).
The body is never used — an intermediary can answer JSON with an ``error``
key. When the origin is unknown the response is treated as proxy-generated.

POST/PUT/DELETE are retried only on 429 and on never-reached failures. The
read-only POSTs (search, document reads, resolve, semantic search,
``legislation_as_of``) may also retry an app-origin 502/503/504 when
``RetryConfig.retry_read_only_posts`` is set; webhook writes and tests never are.

Wait resolution (server-directed wins, clamped to ``backoff_cap``):

1. ``Retry-After`` header (delta-seconds or HTTP-date) on any status; an
   empty or unparseable value counts as absent,
2. on a 429 only: ``RateLimit-Reset`` (draft-6 delta-seconds; LexAPI sends
   ``RateLimit-*`` on every response, so outside a 429 it describes the rate
   window, not a retry time). ``X-RateLimit-*`` is not sent and is ignored,
3. on a 429 (and a 503 ``NATIONAL_SEMANTIC_UNAVAILABLE``): the JSON
   ``retryAfter`` body field,
4. exponential backoff with full jitter.

Numeric hints are delta-seconds; a value above 1e12 is read as epoch
milliseconds and above 1e9 as epoch seconds and converted to a delta. A
negative, non-finite (``nan``, ``inf``) or unconvertible hint counts as
absent, so the wait falls back to the next source or to backoff.

A 429 that reports an exhausted *quota* is never retried — it cannot
succeed before ``resetsAt``. It is recognised by the body's top-level
``code: "QUOTA_EXHAUSTED"`` (API 2.4.0 on), whatever else the response
carries, or, from older servers, by the legacy shape: a ``usage`` block with
``resetsAt`` and neither ``Retry-After`` nor ``retryAfter``
(:func:`is_quota_exhausted`).
"""

from __future__ import annotations

import math
import random
import re
import time
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any

import httpx

#: Above this a numeric hint is epoch *seconds* (1e9 s ≈ 31.7 years of delta).
EPOCH_SECONDS_THRESHOLD = 1_000_000_000
#: Above this a numeric hint is epoch *milliseconds*.
EPOCH_MILLIS_THRESHOLD = 1_000_000_000_000

_IDEMPOTENT_METHODS = frozenset({"GET", "HEAD", "OPTIONS"})

#: Cloudflare could not reach the origin: web server down (521), connection
#: timed out (522), origin unreachable (523). The app never saw the request.
NOT_REACHED_STATUSES = frozenset({521, 522, 523})

#: App-origin statuses a read-only POST may retry under ``retry_read_only_posts``.
READ_ONLY_POST_STATUSES = frozenset({502, 503, 504})


def _default_retry_statuses() -> frozenset[int]:
    return frozenset({429, 502, 503, 504, 520, 521, 522, 523, 524})


def _default_non_idempotent_statuses() -> frozenset[int]:
    return frozenset({429})


@dataclass(frozen=True)
class RetryConfig:
    """Retry policy knobs. ``max_retries=0`` disables retries entirely.

    Attributes:
        max_retries: retries after the first attempt (default 3).
        backoff_base / backoff_cap: full-jitter backoff ``U(0, min(cap,
            base * 2**attempt))`` in seconds; the cap also clamps
            server-directed waits (a cap below the server's requested wait
            shortens it, so the retry may come too early).
        retry_statuses: statuses ever considered for a retry. The
            billing-safety rule (module docstring) still decides per response.
        retry_statuses_non_idempotent: statuses retried for **every**
            POST/PUT/DELETE, webhook writes included, whatever their origin.
            Default ``{429}``. Widening it can duplicate webhooks or test
            deliveries and can double-charge — prefer ``retry_read_only_posts``.
        retry_read_only_posts: also retry the read-only POSTs (search,
            document reads, resolve, semantic search,
            ``legislation_as_of``) on an **app-origin**
            502/503/504, which the API refunds in full. Default off; never
            applies to webhook create/update/test.
    """

    max_retries: int = 3
    backoff_base: float = 0.5
    backoff_cap: float = 30.0
    retry_statuses: frozenset[int] = field(default_factory=_default_retry_statuses)
    retry_statuses_non_idempotent: frozenset[int] = field(
        default_factory=_default_non_idempotent_statuses
    )
    retry_read_only_posts: bool = False

    def __post_init__(self) -> None:
        for name in ("backoff_base", "backoff_cap"):
            value = getattr(self, name)
            if not _finite_non_negative(value):
                raise ValueError(f"{name} must be a finite number of seconds >= 0, got {value!r}")


def _finite_non_negative(value: Any) -> bool:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return False
    try:
        number = float(value)
    except OverflowError:  # an integer too large for a double
        return False
    return math.isfinite(number) and number >= 0


DEFAULT_RETRY_CONFIG = RetryConfig()

#: The longest single sleep (2**31 - 1 milliseconds), so that no sleep call
#: receives a value the platform cannot represent.
MAX_SLEEP_SECONDS = 2_147_483.647


def clamp_wait(seconds: float, config: RetryConfig) -> float:
    """A wait as passed to a sleep call: within ``[0, backoff_cap]`` and
    never above :data:`MAX_SLEEP_SECONDS`."""
    if not math.isfinite(seconds) or seconds < 0:
        return 0.0
    return min(seconds, config.backoff_cap, MAX_SLEEP_SECONDS)


def compute_backoff(attempt: int, config: RetryConfig) -> float:
    """Exponential backoff with full jitter: ``U(0, min(cap, base * 2**attempt))``."""
    growth = 2.0 ** min(attempt, 1000)  # stays finite for any attempt count
    ceiling = min(config.backoff_cap, config.backoff_base * growth)
    return clamp_wait(random.uniform(0, ceiling), config)


def _delta_from_number(value: float) -> float | None:
    """A numeric hint as delta-seconds, converting epoch ms / s defensively.
    A negative or non-finite value (``nan``, ``inf``) is absent."""
    if not math.isfinite(value) or value < 0:
        return None
    if value > EPOCH_MILLIS_THRESHOLD:
        return _rounded_delta(value / 1000.0 - time.time())
    if value > EPOCH_SECONDS_THRESHOLD:
        return _rounded_delta(value - time.time())
    return value


def _rounded_delta(seconds: float) -> float:
    """A wait to a point in time: rounded to the nearest second (halves up),
    and 0 for a point in the past."""
    return float(max(0, math.floor(seconds + 0.5)))


_NUMBER = re.compile(r"[0-9]+(?:\.[0-9]+)?")
_WKDAY = r"(mon|tue|wed|thu|fri|sat|sun)"
_WEEKDAY = r"(monday|tuesday|wednesday|thursday|friday|saturday|sunday)"
_MONTHS = ("jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov", "dec")
_MONTH = r"(" + "|".join(_MONTHS) + r")"
_TIME = r"([0-9]{2}):([0-9]{2}):([0-9]{2})"
_ZONE = r"(?:gmt|utc|\+0000)"
#: IMF-fixdate: ``Sun, 06 Nov 1994 08:49:37 GMT``.
_IMF = re.compile(rf"{_WKDAY}, ([0-9]{{2}}) {_MONTH} ([0-9]{{4}}) {_TIME} {_ZONE}", re.I)
#: RFC 850: ``Sunday, 06-Nov-94 08:49:37 GMT``.
_RFC850 = re.compile(rf"{_WEEKDAY}, ([0-9]{{2}})-{_MONTH}-([0-9]{{2}}) {_TIME} {_ZONE}", re.I)
#: asctime: ``Sun Nov  6 08:49:37 1994`` (day space- or zero-padded), UTC.
_ASCTIME = re.compile(rf"{_WKDAY} {_MONTH} ( [0-9]|[0-9]{{2}}) {_TIME} ([0-9]{{4}})", re.I)


def _trim(value: str) -> str:
    return value.strip(" \t")


def _header_number(value: str) -> float | None:
    """A header's numeric value: ASCII ``[0-9]+(.[0-9]+)?`` after trimming
    spaces and tabs, and finite; anything else (a sign, an exponent, ``.5``,
    ``5.``, ``nan``, ``inf``, other digits) is not a number."""
    text = _trim(value)
    if not _NUMBER.fullmatch(text):
        return None
    number = float(text)
    return number if math.isfinite(number) else None


_MONTH_DAYS = (31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31)


def _is_leap(year: int) -> bool:
    return year % 4 == 0 and (year % 100 != 0 or year % 400 == 0)


def _days_from_civil(year: int, month: int, day: int) -> int:
    """Days from 1970-01-01 to a proleptic Gregorian date (any year >= 0)."""
    year -= month <= 2
    era = year // 400
    yoe = year - era * 400
    doy = (153 * (month + (-3 if month > 2 else 9)) + 2) // 5 + day - 1
    doe = yoe * 365 + yoe // 4 - yoe // 100 + doy
    return era * 146097 + doe - 719468


def _timestamp(year: int, month: int, day: int, hh: int, mm: int, ss: int) -> float | None:
    """Seconds since the epoch for a UTC date, ``None`` for an impossible one
    (30 February, 29 February outside a leap year, day 00, hour 24, minute or
    second 60). Year 0000 is a valid year."""
    days = _MONTH_DAYS[month - 1] + (month == 2 and _is_leap(year))
    if not 1 <= day <= days or hh > 23 or mm > 59 or ss > 59:
        return None
    return float(_days_from_civil(year, month, day) * 86400 + hh * 3600 + mm * 60 + ss)


def _rfc850_year(yy: int, rest: tuple[int, ...], now: float) -> int:
    """RFC 9110 §5.6.7, per timestamp: the latest year ending in ``yy`` whose
    timestamp is not more than 50 years after now."""
    today = datetime.fromtimestamp(now, tz=timezone.utc)
    limit = (today.year + 50, today.month, today.day, today.hour, today.minute, today.second)
    year = limit[0] // 100 * 100 + yy
    if (year, *rest) > limit:
        year -= 100
    return year


def parse_http_date(value: str, now: float | None = None) -> float | None:
    """An HTTP-date (IMF-fixdate, RFC 850 or asctime; case-insensitive) as
    seconds since the epoch, or ``None``. The weekday name is not checked
    against the date; an asctime date is read as UTC."""
    text = _trim(value)
    current = time.time() if now is None else now
    m = _IMF.fullmatch(text)
    if m:
        _, day, mon, year, hh, mm, ss = m.groups()
        return _timestamp(
            int(year), _MONTHS.index(mon.lower()) + 1, int(day), int(hh), int(mm), int(ss)
        )
    m = _RFC850.fullmatch(text)
    if m:
        _, day, mon, yy, hh, mm, ss = m.groups()
        month = _MONTHS.index(mon.lower()) + 1
        rest = (month, int(day), int(hh), int(mm), int(ss))
        return _timestamp(_rfc850_year(int(yy), rest, current), *rest)
    m = _ASCTIME.fullmatch(text)
    if m:
        _, mon, day, hh, mm, ss, year = m.groups()
        return _timestamp(
            int(year), _MONTHS.index(mon.lower()) + 1, int(day), int(hh), int(mm), int(ss)
        )
    return None


def parse_retry_after(value: str) -> float | None:
    """Parse a ``Retry-After`` header: delta-seconds or an HTTP-date.

    A value that is neither counts as absent (``None``). A date in the past
    is a wait of 0; the wait to a date is rounded to the nearest second.
    """
    seconds = _header_number(value)
    if seconds is not None:
        return _delta_from_number(seconds)
    now = time.time()
    when = parse_http_date(value, now)
    if when is None:
        return None
    return _rounded_delta(when - now)


def _usable_seconds(raw: Any) -> float | None:
    """A JSON number (not a ``bool``) >= 0 that is a finite double."""
    if isinstance(raw, bool) or not isinstance(raw, (int, float)):
        return None
    try:
        seconds = float(raw)
    except OverflowError:  # an integer too large for a double
        return None
    if not math.isfinite(seconds) or seconds < 0:
        return None
    return seconds + 0.0  # -0.0 -> 0.0


def _typed_error(body: Any) -> dict[str, Any]:
    """The typed envelope's ``error`` object, or ``{}``."""
    err = body.get("error") if isinstance(body, dict) else None
    return err if isinstance(err, dict) else {}


def _body_retry_after(body: Any) -> float | None:
    """JSON ``retryAfter`` field (delta-seconds; epoch values converted):
    the top-level field when usable, else ``details.retryAfter``:
    ``error.details`` on the typed envelope, the top-level ``details`` on
    the legacy shape."""
    if not isinstance(body, dict):
        return None
    seconds = _usable_seconds(body.get("retryAfter"))
    if seconds is None:
        # The typed envelope (``error`` is an object) carries ``error.details``
        # only; a top-level ``details`` belongs to the legacy shape.
        error = body.get("error")
        details = error.get("details") if isinstance(error, dict) else body.get("details")
        if isinstance(details, dict):
            seconds = _usable_seconds(details.get("retryAfter"))
    return None if seconds is None else _delta_from_number(seconds)


def _is_national_semantic_unavailable(status: int, body: Any) -> bool:
    if status != 503 or not isinstance(body, dict):
        return False
    return bool(_envelope_code(body) == "NATIONAL_SEMANTIC_UNAVAILABLE")


def _envelope_code(body: dict[str, Any]) -> Any:
    """The envelope's own code: ``error.code`` on the typed envelope (``error``
    is an object), the top-level ``code`` on the legacy shape."""
    error = body.get("error")
    return error.get("code") if isinstance(error, dict) else body.get("code")


def server_wait_hint(headers: httpx.Headers, body: Any, status: int | None = None) -> float | None:
    """Resolve the server-directed wait for a failed response, if any.

    ``Retry-After`` applies to any status. ``RateLimit-Reset`` applies to a
    429 only; the JSON ``retryAfter`` to a 429 and to a 503
    ``NATIONAL_SEMANTIC_UNAVAILABLE`` (an incomplete national search).
    ``status=None`` (unknown) consults every source.
    """
    header = headers.get("retry-after")
    if header is not None:
        parsed = parse_retry_after(header)
        if parsed is not None:
            return parsed
    if status is not None and status != 429:
        return _body_retry_after(body) if _is_national_semantic_unavailable(status, body) else None
    reset = headers.get("ratelimit-reset")
    if reset is not None:
        number = _header_number(reset)
        seconds = _delta_from_number(number) if number is not None else None
        if seconds is not None:
            return seconds
    return _body_retry_after(body)


def is_quota_exhausted(status: int, headers: httpx.Headers, body: Any) -> bool:
    """True for a 429 that reports an exhausted quota rather than a rate limit.

    API 2.4.0 on: the code is ``QUOTA_EXHAUSTED`` — the top-level ``code``,
    or ``error.code`` on the typed envelope — whatever else the response
    carries. Fallback for older servers: legacy
    daily-call plans (``"Daily quota exceeded"``) and the legacy monthly
    semantic quota answer 429 with a ``usage`` block carrying ``resetsAt``
    and no ``retryAfter`` / ``Retry-After``.
    """
    if status != 429:
        return False
    if isinstance(body, dict) and "QUOTA_EXHAUSTED" in (
        body.get("code"),
        _typed_error(body).get("code"),
    ):
        return True
    header = headers.get("retry-after")
    if header is not None and parse_retry_after(header) is not None:
        return False
    if not isinstance(body, dict) or _body_retry_after(body) is not None:
        return False
    usage = body.get("usage")
    return isinstance(usage, dict) and isinstance(usage.get("resetsAt"), str)


def is_app_response(headers: httpx.Headers, body: Any = None) -> bool:
    """Whether the LexAPI app itself produced this response (see module doc).

    ``body`` is accepted for signature stability and deliberately ignored.
    """
    return bool(headers.get("x-lexapi-version") or headers.get("ratelimit-limit"))


#: httpcore's message when the connection closes before the response head —
#: the stale keep-alive case. Matched exactly (as a prefix): h11's mid-body
#: "peer closed connection without sending complete message body" also says
#: "without sending" but arrives after the response started, so the app may
#: already have charged. httpx raises both as ``RemoteProtocolError`` with no
#: other state to tell them apart.
PRE_RESPONSE_DISCONNECT = "Server disconnected without sending a response"


def never_reached_app(exc: BaseException) -> bool:
    """Transport failures where the request provably never got to the app:
    connect errors and timeouts, pool exhaustion (nothing was sent), and a
    connection closed before any response byte (see
    :data:`PRE_RESPONSE_DISCONNECT`). A close after part of the response
    arrived is *not* in this set."""
    if isinstance(exc, (httpx.ConnectError, httpx.ConnectTimeout, httpx.PoolTimeout)):
        return True
    return isinstance(exc, httpx.RemoteProtocolError) and str(exc).startswith(
        PRE_RESPONSE_DISCONNECT
    )


def is_retryable_exception(exc: BaseException, method: str = "GET", *, free: bool = False) -> bool:
    """Transport-error retry rule.

    Never-reached failures are safe for any method. Any other transport
    error (read errors and timeouts after the request was sent) is retried
    only for a **free** idempotent operation — on a billed call the app may
    have charged and, with no finished error response, refunds nothing.
    """
    if never_reached_app(exc):
        return True
    return free and method.upper() in _IDEMPOTENT_METHODS and isinstance(exc, httpx.TransportError)


def is_budget_timeout(status: int, body: Any) -> bool:
    """A 503 whose body says ``partialReason: "TIMEOUT"``: the request ran
    out of its fixed server-side budget. Refunded, but a re-run would wait
    the full budget again, so it is never retried automatically."""
    return status == 503 and isinstance(body, dict) and body.get("partialReason") == "TIMEOUT"


def _partial_reason(body: Any) -> Any:
    """``partialReason`` from the top-level body (legacy shape) or from
    ``error.details`` (typed envelope)."""
    if not isinstance(body, dict):
        return None
    if "partialReason" in body:
        return body.get("partialReason")
    err = body.get("error")
    details = err.get("details") if isinstance(err, dict) else None
    return details.get("partialReason") if isinstance(details, dict) else None


def is_incomplete_search(status: int, body: Any) -> bool:
    """A 503 ``partialReason: "SEARCH_INCOMPLETE"``: a national semantic
    search the index could not complete, with nothing left to return.
    Retried at most once per call, and only after a server-directed wait."""
    return status == 503 and _partial_reason(body) == "SEARCH_INCOMPLETE"


def is_repeated_incomplete_search(status: int, headers: httpx.Headers, body: Any) -> bool:
    """An incomplete-search 503 with no wait (neither ``Retry-After`` nor
    ``retryAfter``): the same national semantic search has repeatedly come
    back incomplete, so a retry would too. Never retried automatically."""
    return is_incomplete_search(status, body) and server_wait_hint(headers, body, status) is None


def retry_allowed(
    method: str,
    response: httpx.Response,
    body: Any,
    config: RetryConfig,
    *,
    read_only: bool = False,
    free: bool = False,
    incomplete_retried: bool = False,
) -> bool:
    """The billing-safety decision for one failed response.

    ``incomplete_retried``: this call already retried an incomplete-search
    503 once (:func:`is_incomplete_search`), so another is not retried.
    """
    status = response.status_code
    idempotent = method.upper() in _IDEMPOTENT_METHODS
    if is_quota_exhausted(status, response.headers, body):
        return False
    if is_budget_timeout(status, body):
        return False
    if is_repeated_incomplete_search(status, response.headers, body):
        return False
    if incomplete_retried and is_incomplete_search(status, body):
        return False
    if not idempotent and status in config.retry_statuses_non_idempotent:
        return True  # 429 by default; anything else is an explicit caller opt-in
    if status not in config.retry_statuses:
        return False
    if status == 429 or status in NOT_REACHED_STATUSES:
        return True
    if idempotent:
        return free or is_app_response(response.headers, body)
    return (
        read_only
        and config.retry_read_only_posts
        and status in READ_ONLY_POST_STATUSES
        and is_app_response(response.headers, body)
    )


def retry_wait(
    method: str,
    response: httpx.Response,
    body: Any,
    attempt: int,
    config: RetryConfig,
    *,
    read_only: bool = False,
    free: bool = False,
    incomplete_retried: bool = False,
) -> float | None:
    """Seconds to sleep before retry *attempt*, or ``None`` for "don't retry".

    A server-directed wait is clamped to ``config.backoff_cap``: a cap below
    the server's requested wait shortens it.
    """
    if attempt >= config.max_retries:
        return None
    if not retry_allowed(
        method,
        response,
        body,
        config,
        read_only=read_only,
        free=free,
        incomplete_retried=incomplete_retried,
    ):
        return None
    hint = server_wait_hint(response.headers, body, response.status_code)
    if hint is not None:
        return clamp_wait(hint, config)
    return compute_backoff(attempt, config)
